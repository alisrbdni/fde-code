#!/usr/bin/env python3
"""Render an assistant's conversation_flow.json as a Mermaid flowchart (GitHub renders Mermaid in Markdown).

    python3 scripts/flow_to_mermaid.py forge     # or: clinic
    python3 scripts/flow_to_mermaid.py --all > docs/workflows.md

Speak nodes are amber stadiums, prompt nodes blue boxes; edge labels show the condition: variable comparisons as
`var == value`, LLM conditions shortened, default edges unlabelled. Generated from the JSON, so the diagram can
never drift from what is deployed.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSISTANTS = ROOT / "api" / "function" / "assistants"


def _label(text: str, limit: int = 48) -> str:
    text = re.sub(r"\s+", " ", text).strip().replace('"', "'")
    text = re.sub(r"^The caller (?:has |is |wants to |asks for )?", "", text)
    return (text[: limit - 1] + "…") if len(text) > limit else text


def mermaid(name: str) -> str:
    flow = json.loads((ASSISTANTS / name / "conversation_flow.json").read_text())
    lines = ["flowchart TD"]
    for node in flow["nodes"]:
        title = node.get("name") or node["id"]
        if node["type"] == "speak":
            lines.append(f'  {node["id"]}(["🗣 {title}"]):::speak')
        else:
            lines.append(f'  {node["id"]}["{title}"]:::prompt')
    for edge in flow["edges"]:
        cond = edge.get("condition") or {}
        target = edge["target"].get("node_id")
        if not target:
            continue
        if cond.get("type") == "expression":
            exp = cond["expression"]
            var = exp["left"]["name"].replace("telnyx_conversation_duration_secs", "duration")
            label = f'{var} {exp["op"]} {exp["right"]["value"]}'
            lines.append(f'  {edge["start_node_id"]} == "{label}" ==> {target}')
        elif cond.get("type") == "llm":
            lines.append(f'  {edge["start_node_id"]} -. "{_label(cond.get("prompt", ""))}" .-> {target}')
        else:
            lines.append(f'  {edge["start_node_id"]} --> {target}')
    lines += [
        "  classDef speak fill:#fff3d6,stroke:#d99a00,color:#3d2c00",
        "  classDef prompt fill:#e3eeff,stroke:#2f6fdb,color:#0e2a5c",
    ]
    return "\n".join(lines)


def main(argv: list) -> int:
    names = [p.name for p in sorted(ASSISTANTS.iterdir()) if (p / "conversation_flow.json").exists()]
    if "--all" in argv:
        out = ["# Workflows (generated by scripts/flow_to_mermaid.py)\n",
               "Thick arrows are **variable comparisons** (deterministic), dotted arrows are **LLM conditions**, plain arrows are "
               "the default edge out of a speak node. Amber stadiums are **speak** nodes (said verbatim), blue boxes are "
               "**prompt** nodes.\n"]
        for name in names:
            out += [f"## {name}\n", "```mermaid", mermaid(name), "```\n"]
        print("\n".join(out))
        return 0
    wanted = [a for a in argv if not a.startswith("-")] or names
    for name in wanted:
        print(mermaid(name))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
